import { type Db, TABLE_ORDER } from "./rows";

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (typeof v === "object") return `'${JSON.stringify(v).replaceAll("'", "''")}'::jsonb`;
  return `'${String(v).replaceAll("'", "''")}'`;
};

/** INSERT statements for every row, parents before children. Used to generate supabase/seed.sql. */
export function dbToInsertSql(db: Db): string {
  const out: string[] = ["-- GENERATED by `npm run db:seed-sql` from src/server/seed.ts. Synthetic data only. Do not edit."];
  for (const t of TABLE_ORDER) {
    for (const row of db[t] as unknown as Record<string, unknown>[]) {
      const r = t === "auth.users" ? { ...row, aud: "authenticated", role: "authenticated" } : row;
      const cols = Object.keys(r);
      const name = t === "auth.users" ? t : `public.${t}`;
      out.push(`insert into ${name} (${cols.join(", ")}) values (${cols.map((c) => lit(r[c])).join(", ")});`);
    }
  }
  return out.join("\n") + "\n";
}
